export const PIXEL_GLYPH_WIDTH = 5;
export const PIXEL_GLYPH_HEIGHT = 7;
/** Glyph render scale in grid cells (2x = chunky, readable at tiny sizes). */
export const PIXEL_GLYPH_SCALE = 2;
/** Empty plaque padding around the glyph (cells). */
export const GLYPH_PADDING = 2;

/** 5x7 fill flags for a character; unknown chars fall back to `?`. */
export function getPixelGlyph(char: string): boolean[] {
	const rows = PIXEL_FONT[char.toUpperCase()] ?? PIXEL_FONT["?"];
	if (!rows) throw new Error("Pixel font is missing the fallback glyph");
	return rows.flatMap((row) => [...row].map((cell) => cell === "#"));
}
